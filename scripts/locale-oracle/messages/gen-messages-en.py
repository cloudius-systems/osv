# gen-messages-en.py <lmp C all output> > libc/locale/messages-en.inc
# glibc's English libc messages, as glibc 2.41 prints them in the C locale
# (lmp.c run on the host: LANGUAGE= LC_ALL=C lmp C all); they are also the
# msgids of glibc's "libc" message catalog.
import re, sys

def unesc(s):
    return re.sub(r'\\x([0-9a-f]{2})', lambda m: chr(int(m.group(1), 16)), s)

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

err, sig, gai, reg = {}, {}, {}, {}
for line in open(sys.argv[1], encoding='utf-8'):
    k, n, msg = line.rstrip('\n').split(' ', 2)
    n, msg = int(n), unesc(msg)
    if k == 'strerror' and 0 <= n and msg != 'Unknown error %d' % n:
        err[n] = msg
    elif k == 'strsignal' and 1 <= n <= 31:
        sig[n] = msg
    elif k == 'gai_strerror' and msg != 'Unknown error':
        gai[n] = msg
    elif k == 'regerror':
        reg[n] = msg
nerr = max(err) + 1
print('/*')
print(' * Copyright (C) 2026 Greg Burd')
print(' *')
print(' * This work is open source software, licensed under the terms of the')
print(' * BSD license as described in the LICENSE file in the top-level directory.')
print(' */')
print()
print('// Generated by scripts/locale-oracle/messages/gen-messages-en.py from glibc 2.41\'s')
print('// output (strerror, strsignal, gai_strerror, regerror in the C locale). Do not edit.')
print('// libc/errno/strerror.c defines EN_ERRORS_ONLY and names the table sys_errlist.')
print('#ifndef EN_ERRORS_ONLY')
print('static')
print('#endif')
print('const char *const en_errors[%d] = {' % nerr)
for i in range(nerr):
    print('    %s, // %d' % (cstr(err[i]) if i in err else 'nullptr', i))
print('};')
print('#ifndef EN_ERRORS_ONLY')
print('static const char *const en_signals[32] = {')
print('    nullptr,')
for i in range(1, 32):
    print('    %s, // %d' % (cstr(sig[i]), i))
print('};')
print('static const struct { int code; const char *msg; } en_gai[] = {')
for i in sorted(gai, reverse=True):
    print('    { %d, %s },' % (i, cstr(gai[i])))
print('};')
print('static const char *const en_regerror[%d] = {' % (max(reg) + 1))
for i in range(max(reg) + 1):
    print('    %s, // %d' % (cstr(reg[i]), i))
print('};')
print('#endif')
