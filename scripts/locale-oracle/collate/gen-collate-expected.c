/* Writes tests/tst-locale-collate.inc, the expected output of tests/tst-locale-collate.cc: for each
 * locale, the word list sorted by glibc's strcoll (stable merge sort, ties in input order), the sign
 * of glibc's strcoll and wcscoll for every adjacent pair, and the length and FNV-1a hash of the
 * strxfrm and wcsxfrm output of every word. Run on Linux against the test locales of make-test-locales.sh:
 *   gcc -O1 -o gen scripts/locale-oracle/collate/gen-collate-expected.c
 *   LOCPATH=<out>/dir ./gen > tests/tst-locale-collate.inc
 * The word list is tests/tst-locale-collate-words.h (shared with the test). */
#include <locale.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <wchar.h>
#include "../../../tests/tst-locale-collate-words.h"

#define NW (sizeof collate_words / sizeof *collate_words)

static int sg(int x) { return (x > 0) - (x < 0); }

static void merge_sort(int *v, int *tmp, int n)
{
    if (n < 2) return;
    int h = n / 2;
    merge_sort(v, tmp, h);
    merge_sort(v + h, tmp, n - h);
    int i = 0, j = h, k = 0;
    while (i < h && j < n) tmp[k++] = strcoll(collate_words[v[j]], collate_words[v[i]]) < 0 ? v[j++] : v[i++];
    while (i < h) tmp[k++] = v[i++];
    while (j < n) tmp[k++] = v[j++];
    memcpy(v, tmp, n * sizeof *v);
}

static uint64_t whash(const wchar_t *w, size_t n)
{
    uint64_t h = COLLATE_FNV0;
    for (size_t k = 0; k < n; k++) {
        uint32_t u = (uint32_t)w[k];
        unsigned char b[4] = { u & 0xff, (u >> 8) & 0xff, (u >> 16) & 0xff, u >> 24 };
        h = collate_fnv(b, 4, h);
    }
    return h;
}

int main(void)
{
    puts("/* Generated by scripts/locale-oracle/collate/gen-collate-expected.c on Linux glibc; do not edit. */");
    for (int l = 0; l < (int)(sizeof collate_locales / sizeof *collate_locales); l++) {
        const char *name = collate_locales[l];
        if (!setlocale(LC_ALL, name)) { fprintf(stderr, "no %s\n", name); return 1; }
        int v[NW], tmp[NW];
        for (int i = 0; i < (int)NW; i++) v[i] = i;
        merge_sort(v, tmp, NW);
        printf("static const struct collate_expect expect_%d[] = {\n", l);
        for (int i = 0; i < (int)NW; i++) {
            const char *s = collate_words[v[i]];
            int c = i + 1 < (int)NW ? sg(strcoll(s, collate_words[v[i + 1]])) : 0;
            int wc = 2;
            wchar_t ws[256], wt[256];
            if (i + 1 < (int)NW && mbstowcs(ws, s, 256) != (size_t)-1 &&
                mbstowcs(wt, collate_words[v[i + 1]], 256) != (size_t)-1)
                wc = sg(wcscoll(ws, wt));
            unsigned char x[4096];
            size_t n = strxfrm((char *)x, s, sizeof x);
            printf("    { %d, %d, %d, %zu, 0x%016llxull, ", v[i], c, wc, n,
                   (unsigned long long)collate_fnv(x, n, COLLATE_FNV0));
            size_t m = mbstowcs(ws, s, 256);
            if (m == (size_t)-1) {
                printf("-1, 0 },\n");
            } else {
                wchar_t wx[1024];
                size_t wn = wcsxfrm(wx, ws, 1024);
                printf("%zu, 0x%016llxull },\n", wn, (unsigned long long)whash(wx, wn));
            }
        }
        printf("};\n");
    }
    printf("static const struct collate_expect *const expect_all[] = {");
    for (int l = 0; l < (int)(sizeof collate_locales / sizeof *collate_locales); l++) printf(" expect_%d,", l);
    printf(" };\n");
    return 0;
}
