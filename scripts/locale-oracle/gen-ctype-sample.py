# Generate tests/tst-locale-ctype-sample.h: the expected wide-character
# classes, case mappings and widths in C and C.UTF-8 for a fixed sample of
# code points, read from gen-ctype-oracle dumps of glibc (see README.md).
# The sample is 0..0x2ff, every range boundary in libc/locale/ctype-utf8.inc
# (each run's first and last code point and their outer neighbours), and
# 0x110000, 0x7fffffff and WEOF, which lie outside the dumps: glibc gives
# them no class, the identity mapping and width -1 in both locales.
# Usage: gen-ctype-sample.py ctype-utf8.inc d-glibc-C.txt d-glibc-C.UTF-8.txt
import re
import sys

NCP = 0x110000


def load(path):
    rows = []
    with open(path) as f:
        for cp, line in enumerate(f):
            c, bits, up, lo, w = line.split()
            assert int(c, 16) == cp, line
            rows.append((int(bits, 16), int(up, 16), int(lo, 16), int(w)))
    assert len(rows) == NCP, len(rows)
    return rows


def boundaries(inc):
    pts = set()
    table = None
    for line in open(inc):
        m = re.match(r'static const (?:uint32_t|struct casemap) (\w+)\[', line)
        if m:
            table = m.group(1)
            continue
        if line.startswith('}'):
            table = None
            continue
        if not table or table in ('cls_tab', 'cls_len'):
            continue
        if table.startswith('cls_'):
            for v in re.findall(r'0x[0-9a-f]+', line):
                v = int(v, 16)
                lo, n = v >> 11, (v & 0x7ff) + 1
                pts |= {lo - 1, lo, lo + n - 1, lo + n}
        elif table.startswith('case_'):
            for k in re.findall(r'\{(0x[0-9a-f]+),', line):
                k = int(k, 16)
                lo, step, n = k >> 11, 2 if k >> 10 & 1 else 1, (k & 0x3ff) + 1
                last = lo + (n - 1) * step
                pts |= {lo - 1, lo, lo + 1, last, last + 1}
        elif table == 'width_tab':
            for v in re.findall(r'0x[0-9a-f]+', line):
                lo = int(v, 16) >> 2
                pts |= {lo - 1, lo}
    return {p for p in pts if 0 <= p < NCP}


def main():
    inc, cpath, upath = sys.argv[1:4]
    c, u = load(cpath), load(upath)
    sample = sorted(set(range(0x300)) | boundaries(inc))
    print('// Generated by scripts/locale-oracle/gen-ctype-sample.py from')
    print('// libc/locale/ctype-utf8.inc and gen-ctype-oracle dumps of glibc 2.41')
    print('// C and C.UTF-8 (Debian 13). Do not edit.')
    print('// {cp, C classes, C.UTF-8 classes, widths (C + 1) | (C.UTF-8 + 1) << 2,')
    print('//  C towupper - cp, C towlower - cp, C.UTF-8 towupper - cp, towlower - cp}')
    print('static const struct ctype_row { unsigned cp, cbits, ubits, w; int cup, clo, uup, ulo; }')
    print('ctype_sample[] = {')
    line = ''
    for cp in sample + [0x110000, 0x7fffffff, 0xffffffff]:
        if cp < NCP:
            cb, cu, cl, cw = c[cp]
            ub, uu, ul, uw = u[cp]
        else:
            cb, cu, cl, cw = ub, uu, ul, uw = 0, cp, cp, -1
        d = lambda v: str(v - cp) if v != cp else '0'
        row = '{%#x,%#x,%#x,%d,%s,%s,%s,%s},' % (cp, cb, ub, (cw + 1) | (uw + 1) << 2,
                                                 d(cu), d(cl), d(uu), d(ul))
        if len(line) + len(row) > 100:
            print(line)
            line = ''
        line += row
    print(line)
    print('};')


main()
