# Generate libc/locale/translit-c.inc: what glibc's C locale writes for a
# wide character >= 0x80 on a wide stream, from tr-glibc-C.txt (measured on
# glibc 2.41 by tr.c, see README.md). Code points with no entry write '?'.
# Usage: gen-translit.py tr-glibc-C.txt > libc/locale/translit-c.inc
#
# Layout: tr_cp[] sorted code points; entry i writes the bytes
# tr_str[tr_off[i] .. tr_off[i + 1]).
import sys


def load(path):
    out = []
    with open(path) as f:
        for line in f:
            if line.startswith('ferror='):
                assert line.strip() == 'ferror=0', line
                continue
            p = line.split()
            cp = int(p[0], 16)
            s = bytes.fromhex(p[1]) if len(p) > 1 else b''
            assert all(0x20 <= b < 0x7f for b in s), line
            assert not out or out[-1][0] < cp, line
            out.append((cp, s))
    return out


def cstr(s):
    return ''.join('\\' + chr(b) if chr(b) in '"\\?' else chr(b) for b in s)


def emit(rows):
    o = ['// Generated by scripts/locale-oracle/gen-translit.py from tr-glibc-C.txt',
         '// (glibc 2.41 C locale, Debian 13), see scripts/locale-oracle/README.md.',
         '// Do not edit.']
    o.append('static const uint32_t tr_cp[%d] = {' % len(rows))
    vals = ['0x%x' % cp for cp, _ in rows]
    o += ['    ' + ', '.join(vals[k:k + 10]) + ',' for k in range(0, len(vals), 10)]
    o.append('};')
    offs, n = [], 0
    for _, s in rows:
        offs.append(n)
        n += len(s)
    offs.append(n)
    assert n < 0x10000
    o.append('static const uint16_t tr_off[%d] = {' % len(offs))
    vals = ['%d' % v for v in offs]
    o += ['    ' + ', '.join(vals[k:k + 12]) + ',' for k in range(0, len(vals), 12)]
    o.append('};')
    o.append('static const char tr_str[] =')
    for k in range(0, len(rows), 16):
        o.append('    "%s"' % cstr(b''.join(s for _, s in rows[k:k + 16])))
    o[-1] += ';'
    print('\n'.join(o))
    print('entries %d, bytes %d' % (len(rows), n), file=sys.stderr)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: gen-translit.py tr-glibc-C.txt')
    emit(load(sys.argv[1]))
