# Generate libc/locale/langinfo-builtin.inc: the values glibc reports through
# nl_langinfo_l() for its C and C.UTF-8 locales, as observed on glibc 2.42.
# Usage: scripts/gen-langinfo-builtin.py oracle-C.txt oracle-C.UTF-8.txt > libc/locale/langinfo-builtin.inc
# Input: oracle-C.txt, oracle-C.UTF-8.txt (rows "<name> <cat> <idx> <type> <value>").
import sys

def load(path):
    rows = {}
    for line in open(path):
        p = line.rstrip('\n').split(' ', 4)
        name, cat, idx, typ = p[0], int(p[1]), int(p[2]), p[3]
        val = p[4] if len(p) > 4 else ''
        rows[(cat, idx)] = (name, typ, val)
    return rows

def cstr(bs):
    out = '"'
    for b in bs:
        out += chr(b) if 32 <= b < 127 and chr(b) not in '"\\?' else '\\%03o' % b
    return out + '"'

def entry(name, typ, val):
    if typ == 's':
        return 'S(%s)' % cstr(bytes.fromhex(val))
    if typ == 'b':
        # Read up to the first NUL by the oracle, so only the first byte is the item.
        b = bytes.fromhex(val)[:1]
        return 'B(%s)' % cstr(b)
    if typ == 'd':
        if name == '_NL_MONETARY_CONVERSION_RATE':
            return 'RATE()'
        if name == '_NL_TIME_WEEK_1STDAY':
            return 'D(%su)' % val
        return 'D(%su)' % val
    if typ == 'w':
        cps = [int(x, 16) for x in val.split(',') if x]
        lit = ''.join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else '\\U%08x' % c for c in cps)
        return 'W(U"%s")' % lit
    raise SystemExit('bad type ' + typ)

c, u = load(sys.argv[1]), load(sys.argv[2])
cats = sorted({k[0] for k in c})
print('// Generated by gen-langinfo-builtin.py from glibc 2.42 observations. Do not edit.')
print('// For each category, the nl_langinfo_l() items of glibc\'s C locale, and the')
print('// items whose value differs in C.UTF-8 (codesets and LC_IDENTIFICATION).')
for cat in cats:
    n = max(i for (k, i) in c if k == cat) + 1
    print('static const struct item cat%d_c[%d] = {' % (cat, n))
    for i in range(n):
        if (cat, i) in c:
            name, typ, val = c[(cat, i)]
            print('    /* %3d %-34s */ %s,' % (i, name, entry(name, typ, val)))
        else:
            print('    /* %3d %-34s */ S(""),' % (i, '-'))
    print('};')
    diffs = []
    for i in range(n):
        if (cat, i) not in c: continue
        name, typ, val = c[(cat, i)]
        uname, utyp, uval = u[(cat, i)]
        if typ == 's' and uval != val and name != '_NL_TIME_ERA_ENTRIES':
            diffs.append((i, uname, entry(uname, utyp, uval)))
    print('static const struct override cat%d_utf8[] = {' % cat)
    for i, name, e in diffs:
        print('    { %3d, %s }, /* %s */' % (i, e, name))
    print('    { -1, S("") },')
    print('};')
print('static const struct category builtin[] = {')
for cat in range(13):
    if cat in cats:
        print('    { cat%d_c, sizeof(cat%d_c) / sizeof(cat%d_c[0]), cat%d_utf8 },' % (cat, cat, cat, cat))
    else:
        print('    { nullptr, 0, nullptr },')
print('};')
